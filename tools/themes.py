def key(n):
    n=n.replace('ı','i').replace('İ','I')
    n=unicodedata.normalize('NFKD',n).encode('ascii','ignore').decode()
    return ''.join(w.capitalize() for w in re.split(r'[^A-Za-z0-9]+',n) if w)
def rgb(h): return [int(h[i:i+2],16) for i in (1,3,5)]
def lum(h):
    def c(v):
        v/=255; return v/12.92 if v<=0.03928 else ((v+0.055)/1.055)**2.4
    r,g,b=map(c,rgb(h)); return 0.2126*r+0.7152*g+0.0722*b
def mix(h,o,t):
    a=rgb(h); b=rgb(o); return '#%02X%02X%02X'%tuple(round(x+(y-x)*t) for x,y in zip(a,b))
